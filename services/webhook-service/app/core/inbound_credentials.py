"""Inbound verification secrets, resolved at runtime instead of captured at boot.

INBOUND_SECRETS is the credential this service owns that an operator genuinely has to change after
launch: it is what Stripe, GitHub or a payment gateway signs WITH, and those providers rotate on
their schedule, not ours. Today it is one packed environment string parsed once, so onboarding a new
source — or accepting a provider's rotation — needs a redeploy. That does not stop the rotation
happening; it means it happens through whoever has shell access.

THE DIRECTION MATTERS. Every other credential in the platform authenticates US to somebody.
These authenticate THEM to us, and the provider is already signing with whatever it held when it
sent — a callback in flight has no version to negotiate. So a source resolves to SEVERAL accepted
secrets, current and previous, exactly as the packed `a|b` form already allowed. Accepting only the
newest would reject genuine callbacks as forged, and a rejected event is one the provider will
eventually stop retrying.

THE ENDPOINT SIGNING SECRETS ARE NOT HERE, deliberately. Those are per-endpoint, generated by this
service, returned once to their owner at creation and rotation, and stored with the endpoint. They
are not operator-entered configuration and nothing about that changes.

IT IS THE HOT PATH. Every third-party event lands on `/inbound/{source}`, so the resolved map is
cached for `INBOUND_SECRET_REFRESH_SECONDS` rather than read per request, and the operator surface
invalidates this replica on a write so the common case — enter a secret, replay the provider's test
event — is instant.
"""
from __future__ import annotations

import time

from app.core.secret_store import SecretError

# Stored one row per source, so a new source can be onboarded without rewriting a packed string
# somebody else's source shares. The prefix is what the panel lists.
PREFIX = "INBOUND_SECRET:"


def secret_name(source: str) -> str:
    """The stored name for a source's secret — the single definition of the convention.

    Production only ever PARSES these names (an operator types the name in the panel), so nothing
    here constructs one. It still exists because the convention must be written down once: the
    tests build names with it and the pool parses them, so a change to either side breaks the pair
    immediately instead of leaving two copies of the rule to drift apart.
    """
    return f"{PREFIX}{source}"


class InboundSecretPool:
    def __init__(self, *, secret_store, configured: dict[str, list[str]],
                 refresh_seconds: int, now=time.monotonic) -> None:
        self._store = secret_store
        self._configured = configured          # parsed INBOUND_SECRETS, the fallback
        self._refresh = refresh_seconds
        self._now = now
        self._cached: dict[str, list[str]] | None = None
        self._until = 0.0

    def invalidate(self) -> None:
        """Drop this replica's resolved map. Another replica's cache cannot be reached from here —
        the refresh window still bounds how stale that one may be."""
        self._cached = None
        self._until = 0.0

    async def get(self) -> dict[str, list[str]]:
        """source -> every secret currently accepted from it. A source absent here is untrusted."""
        if self._cached is not None and self._now() < self._until:
            return self._cached
        resolved = await self._resolve()
        self._cached = resolved
        self._until = self._now() + self._refresh
        return resolved

    async def _resolve(self) -> dict[str, list[str]]:
        # Configuration is the base, so a deployment that has stored nothing behaves exactly as it
        # does today and nothing has to be migrated first.
        out = {source: list(values) for source, values in self._configured.items()}
        if self._store is None:
            return out
        for info in await self._store.list_info(tenant=""):
            if not info.name.startswith(PREFIX):
                continue
            source = info.name[len(PREFIX):]
            try:
                accepted = await self._store.accepted(tenant="", name=info.name)
            except SecretError:
                # A row sealed under a KEK we no longer hold must not silently WIDEN trust by
                # leaving the configured value in place unnoticed, nor take the source down by
                # raising on the hot path. The source is dropped: fail-closed, which is what an
                # unverifiable secret means, and the decrypt failure is loud in the panel.
                out.pop(source, None)
                continue
            if accepted:
                # A stored secret REPLACES the configured one rather than adding to it. Keeping
                # both would mean an operator can never retire a leaked secret without a redeploy,
                # which is the whole problem this exists to solve.
                out[source] = list(accepted)
        return out
