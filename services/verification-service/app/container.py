def _pick(registry: dict[str, Builder], driver: str, port_name: str, settings: Settings) -> Any:
    builder = registry.get(driver)
    if builder is None:
        allowed = ", ".join(sorted(registry))
        raise ConfigError(
            f"unknown {port_name} driver: {driver!r} — allowed: {allowed}"
        )
    return builder(settings)


@dataclass
class Container:
    datastore: DataStore
    cache: Cache
    event_bus: EventBus
    queue: Queue
    object_store: ObjectStore
    secrets: SecretsProvider
    token_verifier: TokenVerifier
    rate_limiter: RateLimiter
    telemetry: Telemetry
    audit_sink: Any = None
    clock: Any = None
    # claim_type -> Verifier. Built once at boot so a misconfigured provider fails there rather
    # than on the first customer who tries to verify.
    verifiers: dict = field(default_factory=dict)

    def describe(self) -> list[dict[str, str]]:
        """[{port, driver}] for the service manifest."""
        return [
            {"port": "datastore", "driver": self.datastore.driver},
            {"port": "cache", "driver": self.cache.driver},
            {"port": "event_bus", "driver": self.event_bus.driver},
            {"port": "queue", "driver": self.queue.driver},
            {"port": "object_store", "driver": self.object_store.driver},
            {"port": "secrets", "driver": self.secrets.driver},
            {"port": "token_verifier", "driver": self.token_verifier.driver},
            {"port": "rate_limiter", "driver": self.rate_limiter.driver},
            {"port": "telemetry", "driver": self.telemetry.driver},
        ] + ([{"port": "audit_sink", "driver": self.audit_sink.driver}]
             if self.audit_sink is not None else [])

    def health_probes(self) -> dict[str, Any]:
        """name -> async health() for adapters that support it (readiness)."""
        probes: dict[str, Any] = {}
        for name in ("datastore", "cache", "event_bus", "queue", "object_store", "rate_limiter"):
            adapter = getattr(self, name)
            # Prefer health_state (a reason string: "ok" / "pool exhausted …" / "down") when the
            # adapter offers it, so readiness can name a FULL datastore distinctly from a DOWN one;
            # fall back to the boolean health() every adapter has.
            probe = getattr(adapter, "health_state", None) or getattr(adapter, "health", None)
            if probe is not None:
                probes[name] = probe
        return probes

    async def close(self) -> None:
        for name in ("datastore", "cache", "event_bus", "queue", "object_store", "rate_limiter"):
            adapter = getattr(self, name)
            close = getattr(adapter, "close", None)
            if close is not None:
                try:
                    await close()
                except Exception:
                    pass


def _build_audit_sink(settings: Settings, event_bus) -> Any:
    """The eventbus sink must publish on the SAME bus instance the container hands out — a second
    instance would be a second in-memory broker, so events would vanish in tests and in any
    single-process deployment while the sink still reported success."""
    driver = settings.AUDIT_SINK_DRIVER
    if driver == "eventbus":
        return EventBusAuditSink(event_bus, settings.AUDIT_TOPIC)
    return _pick(_AUDIT_SINK, driver, "audit_sink", settings)


def make_verifier_pool(settings: Settings, secret_store, runtime_config, secrets):
    """The pool the verification path resolves through, so a credential change lands without a
    redeploy. The environment's secrets port stays the fallback, so a deployment that stores
    nothing behaves exactly as it does today."""
    from app.core.verifier_pool import VerifierPool

    def _fallback(name: str) -> str:
        if secrets is None:
            return ""
        try:
            return secrets.get(name) or ""
        except Exception:      # noqa: BLE001 — a missing env secret is "unset", not an outage
            return ""

    return VerifierPool(
        settings, secret_store, runtime_config,
        build=lambda spec, tokens: _verifiers_from(settings, spec, tokens),
        fallback=_fallback,
        ttl_s=settings.PROVIDER_REFRESH_SECONDS,
    )


def _verifiers_from(settings: Settings, providers_spec: str, tokens: dict) -> dict:
    """`claim_type -> verifier` for one already-resolved set of credentials.

    Shares the boot builder's rules rather than restating them: a claim type with no provider gets
    no entry, and two implementations of "which provider verifies what" would eventually disagree
    about which claims this platform answers.
    """
    resolved = settings.model_copy(update={"VERIFY_PROVIDERS": providers_spec})
    return _build_verifiers(resolved, _TokenSecrets(tokens))


class _TokenSecrets:
    """The resolved credentials, shaped like the secrets port so the builder is untouched.

    Rewriting the builder to take a dict would have been a second place that decides how a provider
    is configured, and a divergence there looks exactly like a working provider quietly using a
    stale key.
    """

    def __init__(self, tokens: dict) -> None:
        self._tokens = tokens

    def get(self, name: str) -> str:
        return self._tokens.get(name, "")


def _build_verifiers(settings: Settings, secrets) -> dict:
    """One verifier per claim type the platform says it checks.

    A claim type with no provider gets NO entry — not a null verifier. The difference matters: an
    absent entry means "we do not verify this", which the service refuses outright; a null entry
    would mean "we verify this" and then answer error forever, which looks like an outage rather
    than a decision.
    """
    profiles = settings.verify_profiles
    secret_names = settings.verify_secrets
    out: dict = {}
    for claim, provider in settings.verify_providers.items():
        if provider == "null":
            out[claim] = NullVerifier()
            continue
        if provider in ("manual", "document"):
            continue                       # answered by a human; see the review flow
        token = ""
        name = secret_names.get(provider)
        if name and secrets is not None:
            try:
                token = secrets.get(name) or ""
            except Exception:
                token = ""
        out[claim] = HttpVerifier(provider, profiles.get(provider, {}), token=token,
                                  timeout=settings.VERIFY_TIMEOUT_SECONDS,
                                  allowed_hosts=settings.egress_allowed_hosts)
    return out


def build_container(settings: Settings) -> Container:
    """Resolve every port from config. Fail-fast on any unknown driver."""
    event_bus = _pick(_EVENTBUS, settings.EVENTBUS_DRIVER, "event_bus", settings)
    container = Container(
        datastore=_pick(_DATASTORE, settings.DATASTORE_DRIVER, "datastore", settings),
        cache=_pick(_CACHE, settings.CACHE_DRIVER, "cache", settings),
        event_bus=event_bus,
        queue=_pick(_QUEUE, settings.QUEUE_DRIVER, "queue", settings),
        object_store=_pick(_OBJECTSTORE, settings.OBJECTSTORE_DRIVER, "object_store", settings),
        secrets=_pick(_SECRETS, settings.SECRETS_DRIVER, "secrets", settings),
        token_verifier=_pick(_TOKEN, settings.TOKEN_VERIFIER_DRIVER, "token_verifier", settings),
        rate_limiter=_pick(_RATELIMITER, settings.RATELIMITER_DRIVER, "rate_limiter", settings),
        telemetry=_pick(_TELEMETRY, settings.TELEMETRY_DRIVER, "telemetry", settings),
        audit_sink=_build_audit_sink(settings, event_bus),
        verifiers=_build_verifiers(settings, _pick(_SECRETS, settings.SECRETS_DRIVER, "secrets", settings)),
    )
    import time

    class _SystemClock:
        """Wall clock, injected so tests can drive expiry rather than sleeping."""
        driver = "system"

        def now(self) -> float:
            return time.time()

    container.clock = _SystemClock()
    return container
